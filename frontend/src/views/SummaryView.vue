<script setup>
import { ref, computed, onMounted } from 'vue'
import { useEnquiriesStore } from '../stores/enquiries'
import StatusSelect from '../components/StatusSelect.vue'
import api from '../api/client'
import { formatDate, formatTimeAgo, getChannelBadgeClass } from '../utils/format'

const store = useEnquiriesStore()

const loadingSummary = ref(false)
const rawSummaryText = ref('')
const generatedAt = ref('')
const stats = ref({})

const overdueList = computed(() => store.overdueList)

const topChannel = computed(() => {
  const cb = stats.value.channel_breakdown || {}
  let max = 0
  let top = 'N/A'
  for (const [k, v] of Object.entries(cb)) {
    if (v > max) { max = v; top = k }
  }
  return top
})

const topTrack = computed(() => {
  const ib = stats.value.interest_breakdown || {}
  let max = 0
  let top = 'N/A'
  for (const [k, v] of Object.entries(ib)) {
    if (k !== 'unknown' && v > max) { max = v; top = k }
  }
  return top !== 'N/A' ? top : 'Bootcamp'
})

// Markdown converter for clean HTML rendering
const formattedSummary = computed(() => {
  if (!rawSummaryText.value) return ''
  return rawSummaryText.value
    .replace(/^### (.*$)/gim, '<h3>$1</h3>')
    .replace(/^## (.*$)/gim, '<h2>$1</h2>')
    .replace(/^# (.*$)/gim, '<h1>$1</h1>')
    .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/gim, '<em>$1</em>')
    .replace(/^- (.*$)/gim, '<li>$1</li>')
    .replace(/^\d+\. (.*$)/gim, '<li>$1</li>')
    .replace(/\n\n/gim, '<br/><br/>')
})

async function fetchSummary(force = false) {
  loadingSummary.value = true
  try {
    const res = await api.getWeeklySummary(force)
    rawSummaryText.value = res.data.ai_summary
    stats.value = res.data.stats || {}
    generatedAt.value = res.data.generated_at
    if (force) {
      store.showToast('Weekly AI Summary freshly generated!', 'success')
    }
  } catch (err) {
    rawSummaryText.value = "Failed to load summary. " + err.message
    store.showToast('Could not load summary: ' + err.message, 'error')
  } finally {
    loadingSummary.value = false
  }
}

async function handleStatusChange(id, newStatus) {
  try {
    await store.updateStatus(id, newStatus)
    store.showToast(`Updated status to "${newStatus}"`, 'success')
  } catch (err) {
    store.showToast('Status update failed: ' + err.message, 'error')
  }
}

onMounted(() => {
  fetchSummary(false)
  store.fetchAll()
})
</script>

